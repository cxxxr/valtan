// Real upstream text, slider and toggle gadgets, including native browser IME input.
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import readline from 'node:readline';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {hash} from './bundle.mjs';
const here=path.dirname(fileURLToPath(import.meta.url));
const output=path.resolve(process.argv[2]??'/tmp/valtan-mcclim-gadgets.json');
const fixture=fs.readFileSync(path.join(here,'gadget-checks.lisp'),'utf8');
const snapshot=fs.mkdtempSync(path.join(os.tmpdir(),'valtan-gadget-checks-'));
const fixtureFile=path.join(snapshot,'checks.lisp');fs.writeFileSync(fixtureFile,fixture);
const report={status:'running',complete:false,startedAt:new Date().toISOString(),
  scope:'Real upstream gadgets and callbacks in a nested frame event loop, driven through Chrome pointer, keyboard and native IME events',
  checksSha256:hash(fixture),driverSha256:hash(fs.readFileSync(fileURLToPath(import.meta.url))),checks:[]};
const save=()=>fs.writeFileSync(output,JSON.stringify(report,null,2)+'\n');save();
const child=spawn(process.execPath,[path.join(here,'workbench.mjs')],{stdio:['pipe','pipe','inherit']});
let serial=0, readyResolve, readyReject;
const ready=new Promise((resolve,reject)=>{readyResolve=resolve;readyReject=reject;});
const pending=new Map();
const exit=new Promise(resolve=>child.on('close',(code,signal)=>{
  const error=Error(`Workbench exited: ${JSON.stringify({code,signal})}`);
  readyReject(error);for(const {reject} of pending.values())reject(error);
  pending.clear();resolve({code,signal});
}));
const timer=setTimeout(()=>child.kill('SIGKILL'),70*60*1000);
readline.createInterface({input:child.stdout}).on('line',line=>{
  const message=JSON.parse(line);
  if(message.work){report.work=message.work;save();}
  if(message.loading)process.stdout.write(message.loading+'\n');
  if(message.ready)readyResolve();
  const request=pending.get(message.id);
  if(request){pending.delete(message.id);message.error?request.reject(Error(message.error)):request.resolve(message.result);}
  else if(message.error)readyReject(Error(message.error));
});
const command=(op,fields={})=>new Promise((resolve,reject)=>{
  const id=++serial;pending.set(id,{resolve,reject});child.stdin.write(JSON.stringify({id,op,...fields})+'\n');
});
const evaluate=async source=>{
  const result=await command('eval',{source,timeout:120000});
  assert.equal(result?.ok,true,result?.error);return result.value;
};
const page=expression=>command('page',{expression});
const mouse=params=>command('cdp',{method:'Input.dispatchMouseEvent',params});
async function waitFor(expression){
  const deadline=Date.now()+30000;
  while(!await page(expression)){
    const errors=await page('mcclimTest.errors');assert.deepEqual(errors,[]);
    if(Date.now()>deadline)throw Error('Browser condition timed out: '+expression);
    await new Promise(resolve=>setTimeout(resolve,50));
  }
}
function checked(name){report.checks.push(name);save();console.log('Passed: '+name);}
try {
  await ready;
  const loaded=await command('eval',{file:fixtureFile});assert.equal(loaded?.ok,true,loaded?.error);
  const original=await page('[...mcclimTest.application.windows.keys()][0]');
  const running=await command('eval',{source:'(mcclim-gadget-checks::run)',wait:false});
  await waitFor("mcclimTest.status==='Gadgets ready' && mcclimTest.application.windows.size===2");
  async function point(name,fx=.5,fy=.5){
    const bounds=await evaluate(`(mapcar #'round (mcclim-gadget-checks::bounds 'mcclim-gadget-checks::${name}))`);
    assert.match(bounds,/^\(\([-+\d ]+\)\)$/);
    const [id,x,y,w,h]=bounds.match(/-?\d+/g).map(Number);
    return page(`(()=>{const c=mcclimTest.application.windows.get(${id}).canvas,r=c.getBoundingClientRect();
      return {x:r.left+(${x}+${w}*${fx})*r.width/c.width,y:r.top+(${y}+${h}*${fy})*r.height/c.height};})()`);
  }
  async function click(point){
    await mouse({type:'mouseMoved',...point});
    await mouse({type:'mousePressed',...point,button:'left',clickCount:1});
    await mouse({type:'mouseReleased',...point,button:'left',clickCount:1});
  }
  async function key(key,code=key,text,modifiers=0){
    await command('cdp',{method:'Input.dispatchKeyEvent',params:{type:'keyDown',key,code,modifiers,...(text?{text}:{})}});
    await command('cdp',{method:'Input.dispatchKeyEvent',params:{type:'keyUp',key,code,modifiers}});
  }
  await click(await point('editor',.02,.5));
  await key('a','KeyA','a');
  await evaluate('(mcclim-gadget-checks::check-editor "a")');
  checked('text field receives keyboard text and its value callback');
  // Queue the whole click/key burst together. A native event must not overtake
  // the focus notification generated by the preceding pointer press.
  await evaluate('(mcclim-gadget-checks::prepare-focus-transfer)');
  const bounds=await evaluate("(mapcar #'round (mcclim-gadget-checks::bounds 'mcclim-gadget-checks::editor))");
  const [editorId,editorX,editorY,,editorHeight]=bounds.match(/-?\d+/g).map(Number);
  const target={window:editorId,x:editorX+8,y:editorY+editorHeight/2};
  const burst=[{type:'pointermove',window:original,x:20,y:20},
    {type:'pointermove',...target},{type:'pointerdown',...target,button:0,buttons:1},
    {type:'pointerup',...target,button:0,buttons:0},
    {type:'keydown',window:editorId,key:'a',code:'KeyA'},
    {type:'keyup',window:editorId,key:'a',code:'KeyA'}];
  await page(`for(const event of ${JSON.stringify(burst)})mcclimTest.application.input(event)`);
  await evaluate('(mcclim-gadget-checks::check-editor "a")');
  checked('a batched click and key preserve the first character across focus transfer');
  await command('cdp',{method:'Input.imeSetComposition',params:{text:'日本',selectionStart:0,selectionEnd:2}});
  await evaluate('(mcclim-gadget-checks::check-editor "a")');
  await command('cdp',{method:'Input.imeSetComposition',params:{text:'日本語',selectionStart:0,selectionEnd:3}});
  await command('cdp',{method:'Input.insertText',params:{text:'日本語'}});
  await command('cdp',{method:'Input.insertText',params:{text:'😀'}});
  await evaluate('(mcclim-gadget-checks::check-editor "a日本語😀")');
  checked('native IME commits Japanese text once and preserves supplementary characters');
  await command('cdp',{method:'Input.imeSetComposition',params:{text:'取り消し',selectionStart:0,selectionEnd:4}});
  await command('cdp',{method:'Input.imeSetComposition',params:{text:'',selectionStart:0,selectionEnd:0}});
  await key('ArrowLeft');await key('Backspace');
  await evaluate('(mcclim-gadget-checks::check-editor "a日本😀")');
  await key('Enter');
  await evaluate('(mcclim-gadget-checks::check-editor "a日本😀" 1)');
  checked('composition cancellation, cursor movement, deletion and activation');
  await key('a','KeyA',undefined,2);await key('Delete');
  await evaluate('(mcclim-gadget-checks::check-editor "日本😀" 1)');
  await key('e','KeyE',undefined,2);await key('Backspace');
  await evaluate('(mcclim-gadget-checks::check-editor "日本" 1)');
  checked('Control shortcuts, forward deletion and deletion of a supplementary character');
  await click(await point('toggle'));
  await evaluate('(mcclim-gadget-checks::check-toggle t)');
  await click(await point('toggle'));
  await evaluate('(mcclim-gadget-checks::check-toggle nil)');
  checked('toggle updates its value and invokes callbacks in both directions');
  const from=await point('slider',.05),to=await point('slider',.8);
  await mouse({type:'mouseMoved',...from});
  await mouse({type:'mousePressed',...from,button:'left',clickCount:1});
  await mouse({type:'mouseMoved',...to,button:'left',buttons:1});
  await mouse({type:'mouseReleased',...to,button:'left',clickCount:1});
  await evaluate('(mcclim-gadget-checks::check-slider 70 90)');
  checked('slider drag changes its value and invokes its release callback');
  report.screenshot=path.join(report.work,'gadgets.png');
  await command('screenshot',{file:report.screenshot});
  await click(await point('quit'));
  await waitFor(`globalThis.workbenchResults[${running.evaluationId}]`);
  const completed=await command('evaluation-result',{evaluationId:running.evaluationId});
  assert.equal(completed.ok,true,completed.error);assert.equal(completed.value,'(:GADGET-FRAME-CLOSED)');
  await waitFor('mcclimTest.application.windows.size===1');
  assert.deepEqual(await page('[...mcclimTest.application.windows.keys()]'),[original]);
  assert.deepEqual(await page('mcclimTest.errors'),[]);
  checked('application exit closes the nested frame and returns to the caller');
  const menu=await command('eval',{wait:false,source:`
    (clim:menu-choose '(("First" :value :first) ("Second" :value :second))
      :associated-window (clim:find-pane-named clim:*application-frame* 'valtan-clim-demo::canvas))`});
  await waitFor('mcclimTest.application.windows.size===2');
  await key('Escape');
  await waitFor(`globalThis.workbenchResults[${menu.evaluationId}]`);
  const dismissed=await command('evaluation-result',{evaluationId:menu.evaluationId});
  assert.equal(dismissed.ok,true,dismissed.error);assert.equal(dismissed.value,'(NIL)');
  await waitFor('mcclimTest.application.windows.size===1');
  assert.deepEqual(await page('mcclimTest.errors'),[]);
  checked('Escape still dismisses a popup after the gadget frame exits');
  report.complete=true;report.status='passed';
} catch(error){report.status='failed';report.error=String(error);process.exitCode=1;}
finally {
  child.stdin.end('{"op":"close"}\n');
  const terminal=await exit;clearTimeout(timer);
  if(terminal.code!==0){report.status='failed';report.complete=false;report.terminal=terminal;process.exitCode=1;}
  if(report.work)report.workbench=JSON.parse(fs.readFileSync(path.join(report.work,'report.json'),'utf8'));
  report.finishedAt=new Date().toISOString();save();
}
console.log(`McCLIM gadgets: ${report.status}; report: ${output}`);
